"""The pages of `mh` alone in a real browser (0366): Chromium drives the home page.

The image of the branch serves `mh` through `mh.sh` on the demo tree; the Playwright
image (`tests/support/pages_browser.py`) runs `tests/support/pages_walk.py` on the
host's network. Proven here: search and browse open from the home page and come back,
each under a bound, without a container started by the click (Docker's events); a
console step runs while the page stays open; the tab follows a page of its own server
back to the home page ten times in a row, without F5 (0354). Not proven: `mh.ps1`,
Windows, Docker Desktop (step 36 of `mh-measure.ps1`, by hand).

Heavy (Chromium, a dozen servers started): CI only, where `MEDIA_HYGIENE_E2E_BROWSER`
is set, besides the host folder the step files need (`MEDIA_HYGIENE_E2E_HOST_DIR`).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import signal
import subprocess
import tempfile
import time
import urllib.request
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

import pytest

from tests.support.docker import IMAGE, docker, run_image
from tests.support.pages_browser import BrowserRun, build_browser, run_browser

if TYPE_CHECKING:
    from collections.abc import Iterator

HOST_DIR: Final = os.environ.get("MEDIA_HYGIENE_E2E_HOST_DIR", "")
BROWSER: Final = os.environ.get("MEDIA_HYGIENE_E2E_BROWSER", "") == "1"
pytestmark = [
    pytest.mark.e2e,
    pytest.mark.skipif(
        not (HOST_DIR and BROWSER) or shutil.which("bash") is None,
        reason="browser tests run in CI only (MEDIA_HYGIENE_E2E_BROWSER=1 and "
        "MEDIA_HYGIENE_E2E_HOST_DIR set): Chromium and a dozen servers are heavy",
    ),
]
_WALK: Final = Path(__file__).parents[1] / "support" / "pages_walk.py"
_IMAGE_USER: Final = (
    "id() { echo 1000; }"  # the demo volumes belong to the image's user
)
_STEP_TIMEOUT: Final = 600
_HOME_UP_S: Final = 120  # mh starts its container, then the home server
_PORT: Final = re.compile(r'-p "127\.0\.0\.1:(\d+):')
# Bounds, in ms, generous for a CI runner (the figures themselves go to the log).
_SHOWN_MS: Final = 10_000
_BACK_MS: Final = 10_000
_ROUND_MS: Final = 60_000
_ROUNDS: Final = 10


@pytest.fixture
def served(volumes: dict[str, str]) -> Iterator[tuple[Path, str]]:
    """`mh` alone running in the background, its reports on a host folder.

    Args:
        volumes: The demo's named volumes (data audited by `mh audit` first).

    Yields:
        The folder of the run, and the port of the home page.
    """
    root = Path(tempfile.mkdtemp(dir=HOST_DIR))
    reports = root / "reports"
    reports.mkdir()
    reports.chmod(0o777)  # the image's user writes there, this one removes step files
    mounts = [
        argument
        for kind, name in volumes.items()
        if kind != "reports"
        for argument in ("-v", f"{name}:/{kind}")
    ]
    written = run_image(*mounts, "-v", f"{reports}:/reports", IMAGE, "launcher",
                        "--shell", "bash")  # fmt: skip
    assert written.returncode == 0, written.stderr
    port = _PORT.search(written.stdout)
    assert port, written.stdout
    script = root / "mh.sh"
    script.write_text(written.stdout, "utf-8")
    bash = shutil.which("bash") or "bash"
    environment = {**os.environ, "HOME": str(root)}
    # Trusted script generated by the image under test, in the test's own folder.
    audit = subprocess.run(  # noqa: S603
        [bash, "-c", f"{_IMAGE_USER}; source {script}; mh audit"],
        capture_output=True, text=True, check=False, env=environment,
        timeout=_STEP_TIMEOUT,
    )  # fmt: skip
    assert audit.returncode == 0, audit.stdout + audit.stderr
    with (
        (root / "mh.log").open("w", encoding="utf-8") as log,
        subprocess.Popen(  # noqa: S603
            [bash, "-c", f"{_IMAGE_USER}; source {script}; mh"],
            stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT,
            env=environment, start_new_session=True,
        ) as home,
    ):  # fmt: skip
        try:
            _wait_for_home(port.group(1), home)
            yield root, port.group(1)
        finally:
            os.killpg(home.pid, signal.SIGTERM)
    left = docker("ps", "--quiet", "--filter", f"ancestor={IMAGE}").stdout.split()
    if left:
        docker("rm", "--force", *left)
    shutil.rmtree(root, ignore_errors=True)


def _wait_for_home(port: str, home: subprocess.Popen[bytes]) -> None:
    """Wait until the home page answers: the browser starts faster than `mh` does.

    Args:
        port: The port of the home page.
        home: The `mh` process (its end fails the wait at once).
    """
    deadline = time.monotonic() + _HOME_UP_S
    while time.monotonic() < deadline and home.poll() is None:
        try:
            # A fixed loopback URL of the server under test.
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/", timeout=2):
                return
        except OSError:
            time.sleep(0.5)
    pytest.fail(f"the home page of mh did not answer on port {port}")


def _started(since: float, until: float) -> list[str]:
    """The containers of the image started between two moments (Docker's own clock).

    Args:
        since: The first moment, seconds since the epoch.
        until: The last one.

    Returns:
        The id of each container started.
    """
    shown = "{{.Actor.ID}} {{.Actor.Attributes.image}}"
    events = docker("events", "--since", f"{since:.3f}", "--until", f"{until:.3f}",
                    "--filter", "type=container", "--filter", "event=start",
                    "--format", shown)  # fmt: skip
    return [
        line.split()[0]
        for line in events.stdout.splitlines()
        if line.split()[-1].startswith("media-hygiene")
    ]


def test_pages_of_mh_alone_in_a_real_browser(
    served: tuple[Path, str], capsys: pytest.CaptureFixture[str]
) -> None:
    """Search, browse, a console step and a review from the home page, timed."""
    root, port = served
    shots = root / "walk"
    shots.mkdir()
    build_browser()
    run = BrowserRun(
        name="media-hygiene-e2e-walk",
        scripts=(_WALK,),
        args=(port,),
        network="host",
    )
    failed = run_browser(run, shots)
    mh_log = (root / "mh.log").read_text("utf-8", errors="replace")
    assert not failed, f"{failed}\n--- mh:\n{mh_log}"
    walk: dict[str, Any] = json.loads((shots / "walk.json").read_text("utf-8"))
    with capsys.disabled():
        figures = json.dumps(walk, indent=2)
        print(f"\n0366, measured in Chromium (CI runner): {figures}")  # noqa: T201
    for name in ("search", "browse"):
        if name in walk:
            assert walk[name]["click_to_shown_ms"] < _SHOWN_MS, walk[name]
            assert walk[name]["back_home_ms"] < _BACK_MS, walk[name]
    assert walk["search"]["first_search_ms"] is not None
    assert _started(walk["clicks_from"], walk["clicks_until"]) == []
    console = walk["console"]
    assert console["stayed"], console
    assert "history" in console["said"], console
    assert console["step"]["state"] == "done", console
    assert console["step"]["code"] == 0, console
    rounds = walk["own_server"]
    assert rounds["review"], "no review page available on the demo tree"
    assert len(rounds["rounds_ms"]) == _ROUNDS
    assert max(rounds["rounds_ms"]) < _ROUND_MS, rounds
