"""The real image: `launcher` writes `mh`; `mh audit` runs this very image."""

from __future__ import annotations

import os
import shutil
import subprocess
from typing import TYPE_CHECKING, Final

import pytest

from media_hygiene.paths.docker_run import PUBLISHED_IMAGE
from tests.support.docker import IMAGE, run_image

if TYPE_CHECKING:
    from pathlib import Path

pytestmark = [
    pytest.mark.e2e,
    pytest.mark.skipif(
        shutil.which("docker") is None or shutil.which("bash") is None,
        reason="docker or bash is not available",
    ),
]
# The demo volumes belong to the image's user: `mh` runs as the same one.
_IMAGE_USER = "id() { echo 1000; }"
LOCAL_IMAGE: Final = "media-hygiene"  # MEDIA_HYGIENE_IMAGE of the Dockerfile's `local`


def test_mh_audit_runs_from_the_generated_launcher(
    volumes: dict[str, str], tmp_path: Path
) -> None:
    """The script names the volumes of the run; `mh audit` then succeeds."""
    mounts = [
        argument
        for kind, name in volumes.items()
        for argument in ("-v", f"{name}:/{kind}")
    ]
    written = run_image(*mounts, IMAGE, "launcher", "--shell", "bash")
    assert written.returncode == 0, written.stderr
    assert f'-v "{volumes["journal"]}:/journal"' in written.stdout
    # The local target names itself (TODO 0080): `mh` runs this image, not a pull.
    assert PUBLISHED_IMAGE not in written.stdout
    assert f'{LOCAL_IMAGE} "$@"' in written.stdout
    script = tmp_path / "mh.sh"
    script.write_text(written.stdout, "utf-8")
    bash = shutil.which("bash") or "bash"
    environment = {**os.environ, "HOME": str(tmp_path)}
    # Trusted script generated by the image under test, in the test's own folder.
    audit = subprocess.run(  # noqa: S603
        [bash, "-c", f"{_IMAGE_USER}; source {script}; mh audit"],
        capture_output=True,
        text=True,
        check=False,
        env=environment,
    )
    assert audit.returncode == 0, audit.stdout + audit.stderr


def test_mh_alone_runs_the_step_typed_on_the_demo_tree(
    volumes: dict[str, str], tmp_path: Path
) -> None:
    """`mh` alone: the menu of this very image, then `1` (audit) typed on stdin."""
    mounts = [
        argument
        for kind, name in volumes.items()
        for argument in ("-v", f"{name}:/{kind}")
    ]
    written = run_image(*mounts, IMAGE, "launcher", "--shell", "bash")
    assert written.returncode == 0, written.stderr
    script = tmp_path / "mh.sh"
    script.write_text(written.stdout, "utf-8")
    bash = shutil.which("bash") or "bash"
    environment = {**os.environ, "HOME": str(tmp_path)}
    # Trusted script generated by the image under test, in the test's own folder.
    done = subprocess.run(  # noqa: S603
        [bash, "-c", f"{_IMAGE_USER}; source {script}; mh"],
        input="1\n",
        capture_output=True,
        text=True,
        check=False,
        env=environment,
    )
    assert done.returncode == 0, done.stdout + done.stderr
    assert "mh audit" in done.stderr
    assert "Next time, type it directly: mh audit" in done.stderr
