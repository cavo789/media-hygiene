def test_mh_folders_rewrites_mh_with_the_image_then_audits(
    volumes: dict[str, str], tmp_path: Path
) -> None:
    """0176: `mh folders add` and `remove` run this image's `launcher`; `mh audit` then.

    The added folder is a host folder: Docker cannot mount it inside the read-only demo
    volume of `/data`, so the audit runs once it is removed again, from the file
    written twice by the image.
    """
    mounts = [
        argument
        for kind, name in volumes.items()
        for argument in ("-v", f"{name}:/{kind}")
    ]
    written = run_image(*mounts, IMAGE, "launcher", "--shell", "bash")
    assert written.returncode == 0, written.stderr
    script = tmp_path / "mh.sh"
    script.write_text(written.stdout, "utf-8")
    extra = tmp_path / "Extra photos"
    extra.mkdir()
    bash = shutil.which("bash") or "bash"
    environment = {**os.environ, "HOME": str(tmp_path)}
    line = (
        f'{_IMAGE_USER}; source {script}; mh folders add "{extra}" && '
        f'mh folders remove "{extra}" && mh audit'
    )
    # Trusted script generated by the image under test, in the test's own folder.
    done = subprocess.run(  # noqa: S603
        [bash, "-c", line],
        capture_output=True,
        text=True,
        check=False,
        env=environment,
        timeout=_STEP_TIMEOUT,
    )
    assert done.returncode == 0, done.stdout + done.stderr
    assert f"    {extra}: found" in done.stdout
    assert done.stdout.count(f"Saved, read back from {script}:") == 2
    assert f'-v "{volumes["journal"]}:/journal"' in script.read_text("utf-8")
    assert str(extra) not in script.read_text("utf-8")


# CI sets it: a folder of the runner's own disk, which Docker can bind-mount (0189).
HOST_DIR: Final = os.environ.get("MEDIA_HYGIENE_E2E_HOST_DIR", "")
_SCANNED: Final = re.compile(r"Media files scanned\s*\S\s*([\d.,]+)")


@pytest.mark.skipif(
    not HOST_DIR,
    reason="MEDIA_HYGIENE_E2E_HOST_DIR is not set: no host folder Docker can mount "
    "(the devcontainer's folders live in a volume); CI sets it",
)
def test_launcher_photos_then_folders_add_audit_real_host_folders(
    volumes: dict[str, str],
) -> None:
    """0189: `launcher --photos <host folder>`, `mh audit`, `mh folders add`, audit."""
    root = Path(tempfile.mkdtemp(dir=HOST_DIR))
    first, second = root / "Photos", root / "More photos"
    build_demo(first)
    shutil.copytree(first / "d", second)
    for path in (root, *root.rglob("*")):  # the image's user reads them, read-only
        path.chmod(0o755 if path.is_dir() else 0o644)
    tools = [
        argument
        for kind, name in volumes.items()
        if kind != "data"
        for argument in ("-v", f"{name}:/{kind}")
    ]
    written = run_image(
        *tools, IMAGE, "launcher", "--shell", "bash", "--photos", str(first)
    )
    assert written.returncode == 0, written.stderr
    script = root / "mh.sh"
    script.write_text(written.stdout, "utf-8")
    bash = shutil.which("bash") or "bash"
    line = (
        f"{_IMAGE_USER}; source {script}; mh audit && "
        f'mh folders add "{second}" && mh audit'
    )
    # Trusted script generated by the image under test, in the test's own folder.
    done = subprocess.run(  # noqa: S603
        [bash, "-c", line],
        capture_output=True,
        text=True,
        check=False,
        env={**os.environ, "HOME": str(root)},
        timeout=_STEP_TIMEOUT,
    )
    assert done.returncode == 0, done.stdout + done.stderr
    before, after = (int(re.sub(r"\D", "", n)) for n in _SCANNED.findall(done.stdout))
    assert 0 < before < after
    assert f"    {second}: found" in done.stdout
    assert str(second) in script.read_text("utf-8")
