#!/usr/bin/env python3
"""Write .todos/plan.md from the TODO headers alone: /todo-plan's rules, mechanically.

A plan regenerated by hand drifted (counts, a closed TODO still listed): this script is
its only writer. It reads the records of `todo_parse_backlog.sh` and applies the rules
of `.claude/commands/todo-plan.md`: lots are the connected components of one batch under
"shares a folder", at most 5 TODOs, never Critical with Low; a TODO that waits for the
maintainer (`Needs maintainer`), is locked, or keeps a stale `## Status` waits.

Usage: todo_plan_render.py [todos-dir]   (writes <todos-dir>/plan.md, prints its path)
"""

from __future__ import annotations

import datetime
import re
import subprocess
import sys
from pathlib import Path

RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3}
CRITICAL, LOW = 0, 3
LOT_CAP = 5
SCRIPTS = Path(__file__).resolve().parent
type Todo = dict[str, str]
type Lot = tuple[str, list[Todo]]


def sibling(name: str, todos: Path) -> str:
    """Run a sibling script of this folder on the backlog.

    Returns:
        Its standard output.
    """
    command = [str(SCRIPTS / name), str(todos)]
    return subprocess.run(command, check=True, capture_output=True, text=True).stdout  # noqa: S603


def records(todos: Path) -> list[Todo]:
    """The flat backlog, one record per TODO.

    Returns:
        The records of `todo_parse_backlog.sh`.
    """
    blocks = sibling("todo_parse_backlog.sh", todos).strip().split("\n\n")
    return [
        dict(_field(line) for line in block.splitlines())
        for block in blocks
        if block.strip()
    ]


def _field(line: str) -> tuple[str, str]:
    """One `KEY: value` line (an empty value keeps its key).

    Returns:
        The key and the value.
    """
    key, _, value = line.partition(":")
    return key, value.strip()


def folders(todo: Todo) -> set[str]:
    """The folders of its backtick-quoted paths (a folder path stays itself).

    Returns:
        The folders; brace globs and prose are left out.
    """
    paths = re.findall(r"`([^`]+)`", todo.get("FILES", ""))
    return {
        path.rstrip("/") if path.endswith("/") else str(Path(path).parent)
        for path in paths
        if "{" not in path and " " not in path
    }


def rank(todo: Todo) -> int:
    """Its priority as a number, Medium when missing or unknown.

    Returns:
        0 (Critical) to 3 (Low).
    """
    return RANK.get(todo.get("PRIORITY", ""), RANK["medium"])


def label(todo: Todo) -> str:
    """Its priority as written in the plan.

    Returns:
        The capitalised word.
    """
    return next(word for word, value in RANK.items() if value == rank(todo)).title()


def needs_of(todo: Todo) -> str:
    """Its declared dependencies, as the plan shows them.

    Returns:
        The `Depends` text, or a dash.
    """
    return todo.get("DEPENDS") or "—"


def deps(todo: Todo) -> set[str]:
    """The IDs it depends on.

    Returns:
        The IDs.
    """
    return set(re.findall(r"\d+", todo.get("DEPENDS", "")))


def components(group: list[Todo]) -> list[list[Todo]]:
    """The connected components of a batch: adjacent when sharing a folder.

    Returns:
        The components.
    """
    left, found = list(group), []
    while left:
        lot = [left.pop(0)]
        while touching := [
            t for t in left if folders(t) & set().union(*map(folders, lot))
        ]:
            lot.extend(touching)
            left = [t for t in left if t not in touching]
        found.append(lot)
    return found


def split(component: list[Todo]) -> list[list[Todo]]:
    """Never Critical with Low in one lot; at most LOT_CAP per lot.

    Returns:
        The lots, in priority order.
    """
    ranks = {rank(t) for t in component}
    parts = [component]
    if CRITICAL in ranks and LOW in ranks:
        parts = [
            [t for t in component if rank(t) <= RANK["high"]],
            [t for t in component if rank(t) > RANK["high"]],
        ]
    lots: list[list[Todo]] = []
    for part in parts:
        ranked = sorted(part, key=lambda t: (rank(t), t["ID"]))
        lots.extend(ranked[i : i + LOT_CAP] for i in range(0, len(ranked), LOT_CAP))
    return [lot for lot in lots if lot]


def ordered(lot: list[Todo]) -> list[Todo]:
    """Inside a lot: its dependencies first, then priority, then ID.

    Returns:
        The lot in order.
    """
    ids = {t["ID"] for t in lot}
    done: list[Todo] = []
    pending = sorted(lot, key=lambda t: (rank(t), t["ID"]))
    while pending:
        placed = {t["ID"] for t in done}
        ready = next((t for t in pending if not deps(t) & (ids - placed)), pending[0])
        done.append(ready)
        pending.remove(ready)
    return done


def queue(every: list[Todo]) -> tuple[list[Lot], list[Todo]]:
    """The lots and the standalone TODOs of the runnable backlog.

    Returns:
        The lots (largest first among equal priorities) and the standalone TODOs.
    """
    runnable = [t for t in every if not held(t)]
    batches: dict[str, list[Todo]] = {}
    alone = [t for t in runnable if not folders(t)]
    for todo in runnable:
        if folders(todo):
            batches.setdefault(todo.get("BATCH") or "~unknown", []).append(todo)
    lots: list[Lot] = []
    for batch, group in batches.items():
        for part in (p for c in components(group) for p in split(c)):
            if len(part) > 1:
                lots.append((batch, ordered(part)))
            else:
                alone.extend(part)
    lots.sort(key=lambda lot: (min(map(rank, lot[1])), -len(lot[1])))
    alone.sort(key=lambda t: (rank(t), t["ID"]))
    return lots, alone


def held(todo: Todo) -> bool:
    """Tell whether a TODO stays out of the queue.

    Returns:
        True when it waits for the maintainer, is locked, or keeps a stale status.
    """
    stale = "stale-status" in todo.get("FLAGS", "")
    return bool(todo.get("NEEDS") or todo.get("LOCKED") or stale)


def lot_lines(lots: list[Lot]) -> list[str]:
    """The *Recommended order* table and one block per lot.

    Returns:
        The lines.
    """
    lines = ["| # | Lot | Priority | TODOs | Prompt |", "|---|---|---|---|---|"]
    for number, (batch, lot) in enumerate(lots, 1):
        top = min(lot, key=rank)
        ids = " ".join(t["ID"] for t in lot)
        lines.append(
            f"| {number} | {batch} | {label(top)} | {len(lot)} | `/todo {ids}` |"
        )
    for number, (batch, lot) in enumerate(lots, 1):
        common = set.intersection(*map(folders, lot)) or set().union(*map(folders, lot))
        shared = ", ".join(f"`{name}`" for name in sorted(common)[:6])
        lines += ["", f"### {number}. {batch}", "", f"**Shared folders:** {shared}", ""]
        lines += [
            "| Order | ID | Priority | Title | Depends |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {i} | {t['ID']} | {label(t)} | {t['TITLE']} | {needs_of(t)} |"
            for i, t in enumerate(lot, 1)
        ]
    return lines


def table(title: str, intro: str, rows: list[str]) -> list[str]:
    """A section with a table, or nothing when it has no row.

    Returns:
        The lines.
    """
    return ["", f"## {title}", "", intro, "", *rows] if rows[2:] else []


def anomalies(every: list[Todo], todos: Path) -> list[str]:
    """Authoring issues the author should fix.

    Returns:
        One bullet per issue.
    """
    closed = {p.name.split("_")[1][:4] for p in todos.glob("*/*_*.md")}
    known = closed | {t["ID"] for t in every}
    found = [
        f"- `{Path(t['FILE']).name}`: a `## Status` in the flat backlog — move it."
        for t in every
        if "stale-status" in t.get("FLAGS", "")
    ]
    found += [
        f"- `{Path(t['FILE']).name}`: priority missing or unknown — treated as Medium."
        for t in every
        if t.get("PRIORITY") not in RANK
    ]
    found += [
        f"- `{Path(t['FILE']).name}`: depends on {d}, which does not exist."
        for t in every
        for d in sorted(deps(t) - known)
    ]
    return ["", "## Anomalies", "", *found] if found else []


def render(todos: Path) -> str:
    """The whole plan.

    Returns:
        Its markdown.
    """
    every = records(todos)
    lots, alone = queue(every)
    header, partial = sibling("todo_plan_tables.sh", todos).split("\n", 1)
    today = datetime.datetime.now(tz=datetime.UTC).date()
    lines = [
        "# TODO execution plan",
        "",
        f"> Generated by `.claude/scripts/todo_plan_render.py` on {today} — **do not",
        "> edit by hand**: rerun it. Priority and batching live in the TODO files.",
        ">",
        header,
        "> Lots share a folder, never just a theme. Standalone TODOs are the norm.",
        "",
        "## Recommended order",
        "",
    ]
    if lots:
        lines += lot_lines(lots)
    else:
        lines.append(
            "No lot: see *Standalone*." if alone else "Nothing to run unattended."
        )
    lines += table(
        "Standalone",
        "One `/todo NNNN` each, highest priority first.",
        ["| ID | Priority | Title | Batch |", "|---|---|---|---|"]
        + [
            f"| {t['ID']} | {label(t)} | {t['TITLE']} | {t.get('BATCH')} |"
            for t in alone
        ],
    )
    waiting = sorted(
        (t for t in every if t.get("NEEDS")), key=lambda t: (rank(t), t["ID"])
    )
    lines += table(
        "Waiting for the maintainer",
        "**Not queued** for an unattended run (`Needs maintainer`).",
        ["| ID | Priority | Title | Needs |", "|---|---|---|---|"]
        + [
            f"| {t['ID']} | {label(t)} | {t['TITLE']} | {t['NEEDS']} |" for t in waiting
        ],
    )
    lines += table(
        "Currently in progress",
        "Locked by a running `/todo` session: not queued.",
        ["| ID | Title | Locked since |", "|---|---|---|"]
        + [
            f"| {t['ID']} | {t['TITLE']} | {t['LOCKED']} |"
            for t in every
            if t.get("LOCKED")
        ],
    )
    lines += ["", "## Partially done — remaining work", ""]
    lines += [
        "**Not queued**: reviving one means filing a fresh TODO.",
        partial.rstrip(),
    ]
    lines += anomalies(every, todos)
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write the plan of the backlog given (default `.todos`), and say where."""
    todos = Path(sys.argv[1] if len(sys.argv) > 1 else ".todos")
    plan = todos / "plan.md"
    plan.write_text(render(todos), encoding="utf-8")
    sys.stdout.write(f"{plan}\n")


if __name__ == "__main__":
    main()
